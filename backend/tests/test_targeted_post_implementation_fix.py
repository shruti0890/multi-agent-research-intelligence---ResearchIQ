    def test_18_real_patent_preservation_on_gemini_fallback(self):
        """Retrieved real patents are never replaced with fake data when Gemini is unavailable."""
        gap_data = Agent2GapOutput(
            gaps=[],
            proposed_method=NovelMethodProposal(
                title="Spectral Inversion Detector",
                approach="Spectrogram analysis",
                novelty_score=85,
                rationale="Novel approach"
            )
        )
        real_patent = {
            "patent_id": "US11223344B2",
            "publication_number": "US11223344B2",
            "title": "Real Audio Deepfake Detection System",
            "assignee": "Acoustic Intelligence Inc.",
            "applicant": "Acoustic Intelligence Inc.",
            "inventors": ["Dr. Alice"],
            "abstract": "A neural network system for acoustic verification.",
            "claims": "1. A method for audio verification.",
            "source": "Google Patents",
            "sources": ["Google Patents"],
            "jurisdiction": "US",
            "relevance_score": 88
        }
        with patch("agents.agent_patent.retrieve_multi_source_patents", return_value=([real_patent], {"Google Patents": "SUCCESS"}, "SUCCESS")), \
             patch("agents.agent_patent._classify_patents_with_gemini", side_effect=RuntimeError("RESOURCE_EXHAUSTED")):

            result = search_and_classify_patents(gap_data, "Deepfake audio detection")
            assert result.patent_retrieval_status == "SUCCESS"
            assert result.patent_analysis_status == "retrieval_success_synthesis_failed"
            assert len(result.patents) == 1
            assert result.patents[0].patent_id == "US11223344B2"
            assert result.patents[0].assignee == "Acoustic Intelligence Inc."
            assert result.patents[0].relevance_score == 88
