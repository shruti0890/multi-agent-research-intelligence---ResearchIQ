class TestCandidateSentencePool:
    def test_6_research_tokens_not_unnecessarily_removed(self):
        """Valid research sentences are retained in the candidate pool."""
        text = """
Introduction
Deep learning has revolutionized computer vision and natural language processing.
In this work, we study gradient descent dynamics in deep networks.

Methodology
We formulate the loss function as empirical risk minimization with L2 weight decay.
The parameter updates follow stochastic gradient descent with momentum 0.9.

Results
The proposed algorithm converges in 45 epochs, achieving 98.2% test accuracy.
"""
        paper_dict = {
            "title": "Optimization Dynamics in Deep Learning",
            "full_text": text,
            "coverage_type": "full_paper"
        }
        fact_sheet = compress_paper(paper_dict, paper_id="P-TEST")
        # Fact sheet should retain substantial sentences
        assert len(fact_sheet.all_sentences()) >= 4

    def test_7_technical_sentences_remain_candidates(self):
        """Sentences with technical terminology and hyperparameter settings remain candidates."""
        s = "We set batch size = 64, learning rate = 1e-4, and Adam optimizer with beta1 = 0.9."
        sentences = segment_sentences(s)
        assert len(sentences) == 1
        assert "batch size = 64" in sentences[0]

    def test_8_numerical_and_statistical_sentences_remain_candidates(self):
        """Sentences with p-values, statistics, and percentages are retained by segment_sentences."""
        text = "Our method improved accuracy by 14.5% (p < 0.001, 95% CI [12.1, 16.9]). We report mean ± SD of 88.4 ± 2.1."
        sentences = segment_sentences(text)
        assert len(sentences) == 2
        assert "p < 0.001" in sentences[0]
        assert "88.4 ± 2.1" in sentences[1]

    def test_9_references_are_excluded_from_candidate_pool(self):
        """Pure reference lists are correctly excluded from research candidates."""
        ref_text = """
[1] A. Smith and B. Jones, "Deep speech synthesis," IEEE Trans. Audio, vol. 12, pp. 45-56, 2020.
[2] C. Wang et al., "Voice anti-spoofing," in Proc. Interspeech, 2021, pp. 112-116.
[3] D. Lee, "Neural vocoders," doi:10.1109/TASLP.2022.1234567, 2022.
[4] E. Brown, "Acoustic detection," arXiv:2104.01234, 2021.
"""
        classified = inspect_and_classify_unknown_section(ref_text, "References")
        assert classified == "references"

    def test_10_candidate_pool_diagnostics_correct(self, capsys):
        """Compressing a paper outputs the required candidate pool diagnostics."""
        paper_text = """
Introduction
Speech synthesis has progressed rapidly with neural network models.
Detecting manipulated speech requires understanding acoustic spectral properties.

Methodology
We extract spectrograms and compute log mel filterbank energies.
The classification backbone uses a residual convolutional network.

Results
On the test set, we obtain an EER of 2.1%.
Baseline models achieved an EER of 5.8%.

References
[1] Author A, "Title A," Journal A, 2021.
[2] Author B, "Title B," Journal B, 2022.
"""
        paper_dict = {
            "title": "Speech Synthesis Detection",
            "full_text": paper_text,
            "coverage_type": "full_paper"
        }
        compress_paper(paper_dict, paper_id="P-DIAG")
        captured = capsys.readouterr().out
        assert "P-DIAG Diagnostics:" in captured
        assert "Original raw tokens" in captured
        assert "Research text tokens" in captured
        assert "Excluded non-research tokens" in captured
        assert "Sentence extraction tokens" in captured
        assert "Candidate pool tokens" in captured


