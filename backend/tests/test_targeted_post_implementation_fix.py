class TestPatentMultiSourceEngine:
    def test_11_epo_success(self):
        """EPO OPS returns patents when credentials and API respond successfully."""
        with patch.dict(os.environ, {"EPO_OPS_CONSUMER_KEY": "test_key", "EPO_OPS_CONSUMER_SECRET": "test_secret"}):
            with patch("agents.agent_patent.urllib.request.urlopen") as mock_urlopen:
                # Mock token response + search response
                token_resp = MagicMock()
                token_resp.read.return_value = b'{"access_token": "mock_token"}'
                search_resp = MagicMock()
                search_resp.read.return_value = b'{"ops:world-patent-data": {"ops:biblio-search": {"ops:search-result": {"ops:publication-reference": [{"document-id": {"country": {"$": "EP"}, "doc-number": {"$": "3456789"}, "kind": {"$": "A1"}}}]}}}}'

                mock_urlopen.side_effect = [MagicMock(__enter__=MagicMock(return_value=token_resp)), MagicMock(__enter__=MagicMock(return_value=search_resp))]

                patents, status = _fetch_epo_ops_patents(["deepfake audio"])
                assert status == "SUCCESS"
                assert len(patents) >= 1
                assert patents[0]["patent_id"] == "EP3456789A1"

    def test_12_epo_missing_credentials(self):
        """EPO returns SKIPPED_NO_CREDENTIALS when credentials are not in environment."""
        with patch.dict(os.environ, {"EPO_OPS_CONSUMER_KEY": "", "EPO_OPS_CONSUMER_SECRET": ""}, clear=True):
            patents, status = _fetch_epo_ops_patents(["deepfake audio"])
            assert patents == []
            assert status == "SKIPPED_NO_CREDENTIALS"

    def test_13_lens_missing_credentials(self):
        """Lens returns SKIPPED_NO_CREDENTIALS when LENS_API_TOKEN is not in environment."""
        with patch.dict(os.environ, {"LENS_API_TOKEN": ""}, clear=True):
            patents, status = _fetch_lens_patents(["deepfake audio"])
            assert patents == []
            assert status == "SKIPPED_NO_CREDENTIALS"

    def test_14_google_unavailable_on_503(self):
        """Google Patents marks SOURCE_UNAVAILABLE when server returns 503."""
        import urllib.error
        with patch("agents.agent_patent.urllib.request.urlopen", side_effect=urllib.error.HTTPError("url", 503, "Service Unavailable", {}, None)):
            patents, status = _fetch_google_patents(["deepfake audio"])
            assert patents == []
            assert status == "SOURCE_UNAVAILABLE"

    def test_15_partial_multi_source_success(self):
        """When at least one source succeeds and others are skipped/unavailable, overall is PARTIAL_SUCCESS."""
        mock_patent = {
            "patent_id": "EP1122334A1",
            "publication_number": "EP1122334A1",
            "title": "Voice spoofing detection system",
            "assignee": "Cyber Corp",
            "abstract": "Acoustic spoofing detection using spectrograms.",
            "source": "EPO",
            "sources": ["EPO"],
            "jurisdiction": "EP"
        }
        with patch("agents.agent_patent._fetch_epo_ops_patents", return_value=([mock_patent], "SUCCESS")), \
             patch("agents.agent_patent._fetch_google_patents", return_value=([], "SOURCE_UNAVAILABLE")), \
             patch("agents.agent_patent._fetch_lens_patents", return_value=([], "SKIPPED_NO_CREDENTIALS")), \
             patch("agents.agent_patent._fetch_patentsview_patents", return_value=([], "SOURCE_UNAVAILABLE")), \
             patch("agents.agent_patent._fetch_epmc_patents", return_value=([], "NO_RESULTS")):

            patents, source_statuses, overall_status = retrieve_multi_source_patents("Deepfake audio detection")
            assert len(patents) == 1
            assert overall_status == "PARTIAL_SUCCESS"
            assert source_statuses["EPO"] == "SUCCESS"
            assert source_statuses["Lens"] == "SKIPPED_NO_CREDENTIALS"

    def test_16_all_source_failure(self):
        """When all sources fail or are skipped with 0 patents, status is RETRIEVAL_FAILED."""
        with patch("agents.agent_patent._fetch_epo_ops_patents", return_value=([], "SKIPPED_NO_CREDENTIALS")), \
             patch("agents.agent_patent._fetch_google_patents", return_value=([], "SOURCE_UNAVAILABLE")), \
             patch("agents.agent_patent._fetch_lens_patents", return_value=([], "SKIPPED_NO_CREDENTIALS")), \
             patch("agents.agent_patent._fetch_patentsview_patents", return_value=([], "SOURCE_UNAVAILABLE")), \
             patch("agents.agent_patent._fetch_epmc_patents", return_value=([], "NO_RESULTS")):

            patents, source_statuses, overall_status = retrieve_multi_source_patents("Deepfake audio detection")
            assert patents == []
            assert overall_status == "RETRIEVAL_FAILED"

