class TestFullTextValidation:
    def test_1_large_html_containing_only_abstract_rejected(self):
        """Large HTML payload (15k words of wrapper/ads/nav + abstract) must be rejected."""
        nav_filler = " ".join(["publisher", "journal", "volume", "citation", "metrics", "download", "cookie", "policy"] * 1500)
        html_text = f"<h1>Article Landing Page</h1><p><b>Abstract:</b> We describe synthetic audio detection in general terms.</p><div>{nav_filler}</div>"

        is_valid, reason, stats = validate_full_paper_content(html_text)
        assert is_valid is False
        assert "only abstract/non-research" in reason or "publisher wrapper" in reason

    def test_2_full_research_paper_accepted(self):
        """Genuine research paper with Introduction, Methodology, and Results is accepted."""
        paper_text = """
1. Introduction
Deepfake audio detection is an important challenge in security and digital forensics.
Recent advancements in neural vocoders make synthetic speech difficult to distinguish from genuine human speech.
In this paper, we propose a multi-feature fusion network to capture temporal and spectral artifacts.

2. Methodology
Our proposed architecture extracts MFCC and constant-Q transform features from 16kHz audio clips.
The features are processed by a dual-branch convolutional neural network with bidirectional LSTM layers.
We employ cross-entropy loss combined with center loss to maximize inter-class feature separation.

3. Experimental Results
We evaluated the framework on the ASVspoof 2019 and 2021 evaluation benchmarks.
Our model achieved an equal error rate of 1.42% and minimum tandem detection cost function of 0.052.
The proposed method outperforms standard baseline models across all acoustic conditions.

4. Conclusion
We presented a novel acoustic verification framework for synthetic speech detection.
Future work will investigate cross-codec generalization and low-resource adaptation.
"""
        is_valid, reason, stats = validate_full_paper_content(paper_text)
        assert is_valid is True
        assert reason == "valid_research_paper"
        assert len(stats["research_sections"]) >= 3

    def test_3_abstract_and_funding_only_rejected(self):
        """Paper content containing only abstract and funding notes must be rejected."""
        text = """
Abstract
This paper provides an overview of modern machine learning techniques for signal processing.
We survey recent deep learning architectures and summarize ongoing open questions in the domain.

Funding Information
This research was funded by the National Science Foundation under Grant No. IIS-1900123.
"""
        is_valid, reason, stats = validate_full_paper_content(text)
        assert is_valid is False
        assert "only abstract/non-research" in reason

    def test_4_full_paper_with_unusual_section_names_accepted(self):
        """Full paper with domain-specific section names (e.g. Acoustic Formulation, Case Study) is accepted."""
        text = """
1. Background and Overview
Acoustic feature representation plays a pivotal role in detecting manipulated voices.
We study spectral envelopes and phase inconsistencies generated by generative models.

2. Acoustic Formulation and Architecture
Let x(t) denote the raw audio waveform sampled at 16 kHz.
We compute the short-time Fourier transform with a Hanning window of size 512.
The spectral coefficients are fed to a convolutional residual block with residual skip connections.

3. Case Study and Quantitative Results
On the benchmark corpus, our architecture attains 96.8% accuracy and 0.985 AUROC.
Ablation analysis reveals that high-frequency phase features contribute 4.2% absolute gain.

4. Concluding Remarks
Phase features significantly enhance robustness against acoustic perturbations.
"""
        is_valid, reason, stats = validate_full_paper_content(text)
        assert is_valid is True
        assert reason == "valid_research_paper"

    def test_5_unknown_section_containing_research_preserved(self):
        """Unknown section with substantive research prose and vocabulary is preserved and accepted."""
        unknown_text = """
We investigate the impact of audio compression codecs on synthetic voice detection.
Our experimental pipeline processes 10,000 speech samples encoded with MP3, AAC, and Opus codecs at various bitrates.
The deep convolutional neural network extracts 128-dimensional latent embeddings to perform binary classification.
Experimental evaluation demonstrates that our model maintains 94.5% detection accuracy under 32 kbps compression.
Furthermore, we observe that high-pass filtering removes high-frequency synthetic artifacts produced by neural vocoders.
We analyze the feature distributions using t-SNE visualizations and find well-separated clusters for bona fide speech.
"""
        is_valid, reason, stats = validate_full_paper_content(unknown_text)
        assert is_valid is True
        assert reason == "valid_research_paper"


